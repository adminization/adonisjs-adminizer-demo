import { middleware } from '#start/kernel'
import { controllers } from '#generated/controllers'
import router from '@adonisjs/core/services/router'

router.get('/', [controllers.Articles, 'index']).as('home')
router.get('/articles/:slug', [controllers.Articles, 'show']).as('articles.show')
router.get('/categories/:slug', [controllers.Articles, 'byCategory']).as('categories.show')
router.get('/tags/:slug', [controllers.Articles, 'byTag']).as('tags.show')

router
  .group(() => {
    router.get('signup', [controllers.NewAccount, 'create'])
    router.post('signup', [controllers.NewAccount, 'store'])

    router.get('login', [controllers.Session, 'create'])
    router.post('login', [controllers.Session, 'store'])
  })
  .use(middleware.guest())

router
  .group(() => {
    router.post('logout', [controllers.Session, 'destroy'])
  })
  .use(middleware.auth())
